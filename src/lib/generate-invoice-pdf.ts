
import { jsPDF } from "jspdf";

export type InvoicePDF = {
  invoiceNumber: string;
  customerName: string;
  issueDate: string;
  dueDate: string;
  items: {
    description: string;
    quantity: number;
    unitPrice: number;
    lineTotal: number;
  }[];
  subtotal: number;
  taxRate: number;
  tax: number;
  total: number;
  status: string;
};

const money = (amount: number) =>
  new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
  }).format(amount);

export function generateInvoicePDF(invoice: InvoicePDF) {
  const pdf = new jsPDF();
  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();
  const left = 18;
  const right = pageWidth - 18;

  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(22);
  pdf.text("LedgerFlow", left, 22);

  pdf.setFontSize(16);
  pdf.text("INVOICE", right, 22, { align: "right" });

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(10);
  pdf.text(`Invoice No: ${invoice.invoiceNumber}`, left, 34);
  pdf.text(`Status: ${invoice.status.toUpperCase()}`, right, 34, {
    align: "right",
  });

  pdf.setDrawColor(210);
  pdf.line(left, 41, right, 41);

  pdf.setFont("helvetica", "bold");
  pdf.text("Bill To", left, 51);

  pdf.setFont("helvetica", "normal");
  pdf.text(invoice.customerName || "Customer", left, 58);

  pdf.setFont("helvetica", "bold");
  pdf.text("Invoice Date", 125, 51);
  pdf.text("Due Date", 165, 51);

  pdf.setFont("helvetica", "normal");
  pdf.text(invoice.issueDate || "-", 125, 58);
  pdf.text(invoice.dueDate || "-", 165, 58);

  let y = 73;

  pdf.setFillColor(245, 245, 245);
  pdf.rect(left, y, right - left, 10, "F");

  pdf.setFont("helvetica", "bold");
  pdf.text("Description", left + 3, y + 6.5);
  pdf.text("Qty", 112, y + 6.5, { align: "right" });
  pdf.text("Unit Price", 148, y + 6.5, { align: "right" });
  pdf.text("Amount", right - 3, y + 6.5, { align: "right" });

  y += 17;
  pdf.setFont("helvetica", "normal");

  for (const item of invoice.items) {
    if (y > pageHeight - 55) {
      pdf.addPage();
      y = 20;
    }

    const descriptionLines = pdf.splitTextToSize(
      item.description || "-",
      75
    );

    pdf.text(descriptionLines, left + 3, y);
    pdf.text(String(item.quantity), 112, y, { align: "right" });
    pdf.text(money(item.unitPrice), 148, y, { align: "right" });
    pdf.text(money(item.lineTotal), right - 3, y, {
      align: "right",
    });

    y += Math.max(8, descriptionLines.length * 5 + 3);
  }

  if (y > pageHeight - 48) {
    pdf.addPage();
    y = 20;
  }

  y += 5;
  pdf.setDrawColor(210);
  pdf.line(105, y, right, y);
  y += 9;

  pdf.setFont("helvetica", "normal");
  pdf.text("Subtotal", 135, y);
  pdf.text(money(invoice.subtotal), right - 3, y, {
    align: "right",
  });

  y += 7;
  pdf.text(`Tax (${invoice.taxRate}%)`, 135, y);
  pdf.text(money(invoice.tax), right - 3, y, {
    align: "right",
  });

  y += 9;
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(12);
  pdf.text("Total", 135, y);
  pdf.text(money(invoice.total), right - 3, y, {
    align: "right",
  });

  pdf.setFontSize(9);
  pdf.setFont("helvetica", "normal");
  pdf.text(
    "Generated by LedgerFlow Accounting Suite",
    pageWidth / 2,
    pageHeight - 10,
    { align: "center" }
  );

  pdf.save(`${invoice.invoiceNumber || "invoice"}.pdf`);
}
